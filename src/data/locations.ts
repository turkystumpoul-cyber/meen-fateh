export function getCentersForGovernorate(
  gov: GovernorateName,
  dynamicShops: Shop[] = []
): string[] {
  const staticCenters = Object.keys(GEO_HIERARCHY[gov] ?? {});
  const dynamicCenters = dynamicShops
    .filter((s) => s.governorate === gov && s.center.trim() !== '')
    .map((s) => s.center.trim());

  const merged = new Set<string>([...staticCenters, ...dynamicCenters]);
  return Array.from(merged);
}

export function getVillagesForCenter(
  gov: GovernorateName,
  center: string,
  dynamicShops: Shop[] = []
): string[] {
  if (!center || center === ALL_CENTERS_OPTION) {
    return [];
  }

  const staticVillages = GEO_HIERARCHY[gov]?.[center] ?? [];
  const dynamicVillages = dynamicShops
    .filter(
      (s) =>
        s.governorate === gov &&
        s.center === center &&
        s.village.trim() !== ''
    )
    .map((s) => s.village.trim());

  const merged = new Set<string>([...staticVillages, ...dynamicVillages]);
  return Array.from(merged);
}
